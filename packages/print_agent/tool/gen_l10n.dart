// Sinh chuỗi đa ngôn ngữ của module từ l10n/{vi_VN,en_US}.json:
//
//   cd packages/print_agent && fvm dart run tool/gen_l10n.dart
//
// - lib/src/presentation/l10n/agent_locale_keys.dart: `LocaleKeys` (cùng kiểu
//   app EasyPOS: `nhom_khoa`, khoá có @tham_so thì thêm hàm `nhom_khoaTr`).
// - lib/src/presentation/l10n/agent_translations.dart: bảng dịch cho GetX.
import 'dart:convert';
import 'dart:io';

final RegExp _param = RegExp(r'(?<![a-zA-Z0-9._%+-])@([a-zA-Z_][a-zA-Z0-9_]*)');
const _langs = ['vi_VN', 'en_US'];
const _out = 'lib/src/l10n';

void main() {
  final tables = {
    for (final lang in _langs)
      lang: _flatten(
        jsonDecode(File('l10n/$lang.json').readAsStringSync())
            as Map<String, dynamic>,
      ),
  };
  final vi = tables['vi_VN']!;
  final keys = vi.keys.toList()..sort();
  for (final lang in _langs.skip(1)) {
    final miss = keys.where((k) => !tables[lang]!.containsKey(k));
    if (miss.isNotEmpty) stderr.writeln('$lang thiếu: ${miss.join(', ')}');
  }

  final k = StringBuffer()
    ..writeln('// GENERATED by tool/gen_l10n.dart — không sửa tay.')
    ..writeln(
      '// ignore_for_file: constant_identifier_names, non_constant_identifier_names',
    )
    ..writeln()
    ..writeln("import 'package:get/get.dart';")
    ..writeln()
    ..writeln(
      '/// Khoá chuỗi của module Agent (dịch bằng `.tr` / hàm `...Tr`).',
    )
    ..writeln('abstract final class LocaleKeys {');
  for (final key in keys) {
    final text = vi[key]!;
    k
      ..writeln('  /// "${text.replaceAll('\n', ' ')}"')
      ..writeln("  static const $key = '$key';");
    final params = {for (final m in _param.allMatches(text)) m.group(1)!};
    if (params.isNotEmpty) {
      final args = params.map((p) => 'required Object $p').join(', ');
      final map = params.map((p) => "'$p': '\$$p'").join(', ');
      k.writeln('  static String ${key}Tr({$args}) => $key.trParams({$map});');
    }
    k.writeln();
  }
  k.writeln('}');
  File('$_out/agent_locale_keys.dart').writeAsStringSync(k.toString());

  final t = StringBuffer()
    ..writeln('// GENERATED by tool/gen_l10n.dart — không sửa tay.')
    ..writeln()
    ..writeln(
      '/// Bảng dịch của module Agent cho GetX (`Get.addTranslations`).',
    )
    ..writeln('const Map<String, Map<String, String>> agentTranslations = {');
  for (final lang in _langs) {
    t.writeln("  '$lang': {");
    final table = tables[lang]!;
    for (final key in keys) {
      final v = table[key];
      if (v == null) continue;
      t.writeln("    '$key': ${jsonEncode(v).replaceAll(r'$', r'\$')},");
    }
    t.writeln('  },');
  }
  t.writeln('};');
  File('$_out/agent_translations.dart').writeAsStringSync(t.toString());
  stdout.writeln('Đã sinh ${keys.length} khoá.');
}

Map<String, String> _flatten(Map<String, dynamic> json) => {
  for (final g in json.entries)
    for (final e in (g.value as Map<String, dynamic>).entries)
      '${g.key}_${e.key}': e.value.toString(),
};
